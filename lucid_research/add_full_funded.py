"""Add long-run (2008-25 starts) funded stats to app/orb_validated.py for every size x drawdown type, same
setting (12% of MLL, hold to close, $1,000 payouts after MLL+$300) as dashboard_data.funded_job."""
import json, numpy as np, sys
from multiprocessing import Pool
sys.path.insert(0, "..")
import dashboard_data as DDm
from lucid_sizes import SIZES
from app.orb_validated import DATA

def job(a):
    size, kind = a
    L, g = DDm.lg(); A = SIZES[size]; risk = max(0.12 * A["mll"], 1.0)
    paths = [list(range(s, min(s + 250, g.D))) for s in np.where((g.year >= 2008) & (g.year <= 2025))[0][::2]]
    R = [DDm.funded_run([L.get(x) for x in p], A, risk, kind) for p in paths]
    fs = np.array([r[2] if r[2] else np.nan for r in R])
    return size, kind, dict(p1_full=round(float(np.mean([len(r[0]) > 0 for r in R])) * 100),
                            bb_full=round(float(np.mean([r[1] and r[2] is None for r in R])) * 100),
                            first_full=float(np.nanmedian(fs)), cash_full=round(float(np.mean([0.9 * sum(r[0]) for r in R]))))

if __name__ == "__main__":
    with Pool(6) as pool: R = pool.map(job, [(s, k) for s in SIZES for k in ("eod", "intraday", "static")])
    for s, k, o in R:
        DATA["funded"][s][k].update(o)
        f = DATA["funded"][s][k]
        print(s, k, f"paid {o['p1_full']}% (2020-25 {f['p1']}%, now {f['p1_now']}%) blown {o['bb_full']}% (2020-25 {f['bb']}%) first {o['first_full']:.0f}d cash ${o['cash_full']}")
    DATA["note"] += " Funded *_full = starts 2008-25."
    open("../app/orb_validated.py", "w").write('"""Validated KhomaVolume numbers (generated by lucid_research/dashboard_data.py + add_full_history.py + add_full_funded.py — do not hand-edit)."""\nDATA = ' + json.dumps(DATA, default=float) + "\n")
    print("wrote")
