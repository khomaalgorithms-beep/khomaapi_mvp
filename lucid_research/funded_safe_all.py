"""Selected FUNDED SAFE rule (12% MLL risk, take-profit 2R, first $500 asap then half risk + $1,000 payouts with cushion)
vs current funded mode, every size x drawdown type: long run (2008-25), 2020-25, 2025 starts. Writes into app/orb_validated.py."""
import json, numpy as np, sys
from multiprocessing import Pool
sys.path.insert(0, "..")
import funded_safe as FS
from lucid_sizes import SIZES
from app.orb_validated import DATA
import dashboard_data as DDm

def job(a):
    size, kind, safe = a
    S = FS.setup(); L, g = S["L"], S["g"]; A = SIZES[size]; risk = 0.12 * A["mll"]
    old = DDm.DD.__init__
    out = {}
    for lab, x, y in (("full", "2008-03-01", "2025-10-09"), ("good", "2020-01-01", "2025-10-09"), ("now", "2025-01-01", "2025-10-09")):
        st = np.where((g.days >= np.datetime64(x).astype(np.int64)) & (g.days <= np.datetime64(y).astype(np.int64)))[0][::2]
        R = []
        for s in st:
            seq = [L.get(i) for i in range(s, min(s + 250, g.D))]
            R.append(FS.run_kind(seq, A, risk, 2.0 if safe else None, "E" if safe else "A", kind))
        k = np.array([r[0] for r in R]); f = np.array([r[1] or 10**9 for r in R])
        out[lab] = dict(p120=round(float(np.mean(f <= 120)) * 100), paid=round(float(np.mean(f < 10**9)) * 100),
                        bb=round(float(np.mean((k == "blown") & (f == 10**9))) * 100), alive=round(float(np.mean(k != "blown")) * 100),
                        med=float(np.median(f[f < 10**9])) if (f < 10**9).any() else None, cash=round(float(np.mean([0.9 * sum(r[2]) for r in R]))))
    return size, kind, safe, out

if __name__ == "__main__":
    with Pool(7) as pool: R = pool.map(job, [(s, k, sf) for s in SIZES for k in ("eod", "intraday", "static") for sf in (False, True)])
    for s, k, sf, o in R:
        if sf:
            DATA["funded"][s][k]["safe"] = dict(risk=round(0.12 * SIZES[s]["mll"]), risk_after=round(0.06 * SIZES[s]["mll"]), tp_r=2.0,
                                                cushion=round(1300 + 4 * 0.06 * SIZES[s]["mll"]), **{f"{m}_{lab}": v for lab, d in o.items() for m, v in d.items()})
        print(f"{s:5} {k:8} {'SAFE' if sf else 'std '} " + " || ".join(f"{lab}: paid {d['paid']}% (<=120d {d['p120']}%) bb {d['bb']}% alive {d['alive']}% med {d['med'] or 0:.0f}d ${d['cash']}" for lab, d in o.items()))
    DATA["note"] += " Funded safe = 12% MLL, TP 2R, first $500 asap then half risk (lucid_research/funded_safe*.py)."
    open("../app/orb_validated.py", "w").write('"""Validated KhomaVolume numbers (generated by lucid_research/dashboard_data.py + add_full_history.py + add_full_funded.py + funded_safe_all.py — do not hand-edit)."""\nDATA = ' + json.dumps(DATA, default=float) + "\n")
    print("wrote")
