"""Live-cash calculator data: per-trade R stats of the exact live rule for two planning bases
(full history 2008-26, last 10 years). Writes DATA['cash'] into app/orb_validated.py."""
import json, sys, numpy as np
sys.path.insert(0, "..")
import dashboard_data as DDm
from app.orb_validated import DATA
L, g = DDm.lg()
def stats(lo):
    lo_i = np.searchsorted(g.days, np.datetime64(lo).astype(np.int64))
    ds = np.array(sorted(d for d in L if d >= lo_i)); r = np.array([L[d]["net"] / L[d]["rct"] for d in ds])
    eq = np.cumsum(r); ddR = float(-(eq - np.maximum.accumulate(np.r_[0, eq])[1:]).min())
    mo = np.array([str(g.dates[d])[:7] for d in ds]); allm = sorted(set(mo))
    # include months with no trades as 0
    first, last = str(g.dates[lo_i])[:7], str(g.dates[ds[-1]])[:7]
    y0, m0 = map(int, first.split("-")); y1, m1 = map(int, last.split("-")); n_m = (y1 - y0) * 12 + (m1 - m0) + 1
    mr = np.array([r[mo == m].sum() for m in allm] + [0.0] * (n_m - len(allm)))
    yr = g.year[ds]; ys = {int(y): float(r[yr == y].sum()) for y in sorted(set(yr))}
    full = np.zeros(g.D); full[ds] = r; cs = np.cumsum(full[lo_i:]); w12 = float((cs[252:] - cs[:-252]).min())
    last12 = float(r[g.days[ds] >= np.datetime64("2025-10-10").astype(np.int64)].sum())
    return dict(ddR=round(ddR, 1), perMonthR=round(float(r.sum()) / n_m, 3), p10=round(float(np.percentile(mr, 10)), 2),
                p50=round(float(np.percentile(mr, 50)), 2), p90=round(float(np.percentile(mr, 90)), 2), loseM=round(float(np.mean(mr < 0)) * 100),
                worstYearR=round(min(ys.values()), 1), worstYear=min(ys, key=ys.get), worst12R=round(w12, 1), last12R=round(last12, 1), months=n_m)
DATA["cash"] = dict(full=stats("2008-03-01"), ten=stats("2016-10-10"))
open("../app/orb_validated.py", "w").write('"""Validated KhomaVolume numbers (generated by lucid_research/dashboard_data.py + add_full_history.py + add_full_funded.py + funded_safe_all.py + equity_full.py + cash_stats.py — do not hand-edit)."""\nDATA = ' + json.dumps(DATA, default=float) + "\n")
print(json.dumps(DATA["cash"], indent=1))
