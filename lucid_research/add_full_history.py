"""Add the full-history (2008-26) pass rate to app/orb_validated.py for every size x drawdown x preset, at the
preset's already-chosen risk fraction (selection unchanged), so the dashboard can headline the honest long-run number."""
import json, re, numpy as np, sys
from multiprocessing import Pool
sys.path.insert(0, "..")
import dashboard_data as DDm
from lucid_sizes import SIZES
from app.orb_validated import DATA

def job(a):
    size, kind, pr, frac = a
    L, g = DDm.lg(); A = SIZES[size]
    st = np.where((g.days >= np.datetime64("2008-03-01").astype(np.int64)) & (g.days <= np.datetime64("2026-10-09").astype(np.int64)))[0]
    res = [DDm.eval_run([L.get(x) for x in range(s, min(s + 180, g.D))], A, frac * A["mll"], kind) for s in st]
    return size, kind, pr, float(np.mean([r[0] for r in res]))

if __name__ == "__main__":
    jobs = [(s, k, pr, v["frac"]) for s, d in DATA["presets"].items() for k, dd in d.items() for pr, v in dd.items()]
    with Pool(6) as pool: R = pool.map(job, jobs)
    for s, k, pr, p in R:
        DATA["presets"][s][k][pr]["pass_full"] = round(p * 100)
        if k == "eod": print(s, k, pr, round(p * 100), "| 2020-26", DATA["presets"][s][k][pr]["pass_"], "| now", DATA["presets"][s][k][pr]["pass_now"])
    DATA["note"] += " pass_full = rolling starts 2008-26 (includes the weak 2008-19 years)."
    src = '"""Validated KhomaVolume numbers (generated by lucid_research/dashboard_data.py + add_full_history.py — do not hand-edit)."""\nDATA = ' + json.dumps(DATA, default=float) + "\n"
    open("../app/orb_validated.py", "w").write(src); print("wrote")
