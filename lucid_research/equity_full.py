"""Dashboard equity curve = the EXACT live rule (10:30 with-trend, stop 0.2 ATR, real costs) over the full history
2008-03 .. 2026-10 (includes the flat 2009-2019 decade). Writes DATA['equity'] in app/orb_validated.py."""
import json, sys, numpy as np
sys.path.insert(0, "..")
import dashboard_data as DDm
from app.orb_validated import DATA
L, g = DDm.lg()
days = sorted(L); R = np.array([L[d]["net"] / L[d]["rct"] for d in days]); months = [str(g.dates[d])[:7] for d in days]
ms = sorted(set(months)); mo = np.array(months); cum = []; c = 0.0
for m in ms:
    c += R[mo == m].sum(); cum.append(round(c, 2))
eq = np.cumsum(R); dd = (eq - np.maximum.accumulate(np.r_[0, eq])[1:]).min()
yr = {}
for y in range(int(g.year[days[0]]), int(g.year[days[-1]]) + 1):
    x = R[g.year[np.array(days)] == y]
    yr[y] = dict(n=int(len(x)), r=round(float(x.sum()), 1), pf=round(float(x[x > 0].sum() / -x[x < 0].sum()), 2), win=round(float((x > 0).mean()) * 100))
w = R > 0
DATA["equity"] = dict(months=ms, cumR=cum, n=int(len(R)), win=round(float(w.mean()) * 100), pf=round(float(R[w].sum() / -R[~w].sum()), 2),
                      totalR=round(float(R.sum()), 1), maxddR=round(float(dd), 1), years=yr, start=ms[0], end=ms[-1],
                      pf10=1.30, flat_years=9.9)
open("../app/orb_validated.py", "w").write('"""Validated KhomaVolume numbers (generated by lucid_research/dashboard_data.py + add_full_history.py + add_full_funded.py + funded_safe_all.py + equity_full.py — do not hand-edit)."""\nDATA = ' + json.dumps(DATA, default=float) + "\n")
print({k: DATA["equity"][k] for k in ("n", "win", "pf", "totalR", "maxddR", "start", "end")})
